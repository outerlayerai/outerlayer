/**
 * Synthetic eval fixtures for the topics extraction layer.
 *
 * Each fixture is a miniature transcript in the preprocessor's span shape,
 * modeled on a REAL failure class observed on the dogfood corpus — but with
 * fully synthetic content, so this file is safe for a public repo. The
 * expectation encodes what a correct extraction MUST do with it.
 *
 * Categories mirror the failure taxonomy the prompts are tuned against:
 *  - gate:        harness-only session — the deterministic trivial gate fires
 *  - trivialTask: small-but-real work — task described plainly, never NONE,
 *                 never narrated as harness mechanics
 *  - noopIssues:  by-design halt — issues must be NONE
 *  - failIssues:  genuine malfunction — issues non-NONE, single mechanism
 *  - steerDrop:   relayed peer/agent turns — nothing mined as a correction
 *  - steerKind:   session-scoped instruction — never rule/preference
 */

import type { TracePreprocessorSpan } from '../src/trace-preprocessor';

export interface Fixture {
  key: string;
  category: 'gate' | 'trivialTask' | 'noopIssues' | 'failIssues' | 'steerDrop' | 'steerKind';
  spans: TracePreprocessorSpan[];
}

const ts = (n: number) => `2026-07-01 10:00:${String(n).padStart(2, '0')}.000000000`;
let id = 0;
// Every fixture hangs under an agent.session root, matching real capture:
// the preprocessor renders the SPAN TREE, so orphaned spans (a parent id
// that resolves to nothing) silently drop out of the document.
const span = (name: string, input: string, output = '', type = 'SPAN'): TracePreprocessorSpan => ({
  id: `s${(id += 1)}`,
  parentId: 'session-root',
  name,
  type,
  timestamp: ts(id),
  input,
  output,
});
const user = (input: string) => span('agent.turn.user', input);
const assistant = (output: string) => span('agent.turn.assistant', '', output, 'GENERATION');
const sessionRoot = (): TracePreprocessorSpan => ({
  id: 'session-root',
  parentId: '',
  name: 'agent.session',
  type: 'SPAN',
  timestamp: ts(0),
  input: '',
  output: '',
});
const withRoot = (spans: TracePreprocessorSpan[]): TracePreprocessorSpan[] => [sessionRoot(), ...spans];

