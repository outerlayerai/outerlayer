import { describe, expect, it } from 'vitest';
import { classifyTree } from '../../classify';
import { emitTree } from '../index';
import { fixtureInput } from '../test-fixture';

describe('emitTree — claude-code target (full tier)', () => {
  it('compiles instructions to root/nested CLAUDE.md, skills to .claude/skills/, commands, and mcp passthrough', () => {
    const result = emitTree(fixtureInput(['claude-code']));

    expect(result.errors).toEqual([]);
    expect(result.warnings).toEqual([]);
    expect(result.copies).toEqual([
      { toPath: '.claude/skills/deploy-checklist/scripts/run.sh', fromSourcePath: '.outerlayer/skills/deploy-checklist/scripts/run.sh' },
      { toPath: '.claude/skills/onboarding/assets/logo.png', fromSourcePath: '.outerlayer/skills/onboarding/assets/logo.png' },
    ]);
    expect(result.files).toEqual([
      {
        path: '.claude/commands/ship.md',
        content:
          '---\ndescription: Ship the current branch.\nargument-hint: <version>\n---\n' +
          '<!-- generated by OuterLayer from .outerlayer/commands/ship.md — edit the source, not this file -->\n' +
          'Run the ship script.\n',
      },
      {
        path: '.claude/skills/deploy-checklist/SKILL.md',
        content:
          '---\nname: deploy-checklist\ndescription: Steps to deploy safely.\n---\n' +
          '<!-- generated by OuterLayer from .outerlayer/skills/deploy-checklist/SKILL.md — edit the source, not this file -->\n' +
          'Run the checklist.\n',
      },
      {
        path: '.claude/skills/onboarding/references/setup.md',
        content:
          '<!-- generated by OuterLayer from .outerlayer/skills/onboarding/references/setup.md — edit the source, not this file -->\n' +
          'Install dependencies.\n',
      },
      {
        path: '.claude/skills/onboarding/SKILL.md',
        content:
          '---\nname: onboarding\ndescription: Onboard a new engineer.\n---\n' +
          '<!-- generated by OuterLayer from .outerlayer/skills/onboarding/SKILL.md — edit the source, not this file -->\n' +
          'Read the docs.\n',
      },
      {
        path: '.mcp.json',
        content:
          '{\n  "mcpServers": {\n    "api": {\n      "url": "${API_URL:-https://api.example.com}",\n      "headers": {\n        "Authorization": "${API_TOKEN}"\n      },\n      "type": "http",\n      "oauth": true\n    }\n  }\n}\n',
      },
      {
        path: 'apps/api/CLAUDE.md',
        content:
          '<!-- generated by OuterLayer from apps/api/.outerlayer/AGENTS.md — edit the source, not this file -->\n' +
          'API scope instructions.\n',
      },
      {
        path: 'CLAUDE.md',
        content:
          '<!-- generated by OuterLayer from .outerlayer/AGENTS.md — edit the source, not this file -->\n' + 'Root instructions.\n',
      },
    ]);
  });

  it('preserves a command namespace subpath under .claude/commands/ while a flat command stays at the root of it', () => {
    const paths = ['.outerlayer/commands/ship.md', '.outerlayer/commands/deploy/preview/ship.md'];
    const contents = new Map([
      ['.outerlayer/commands/ship.md', 'Flat.\n'],
      ['.outerlayer/commands/deploy/preview/ship.md', 'Nested.\n'],
    ]);
    const result = emitTree({ entries: classifyTree(paths).entries, contents, assetPaths: [], targets: ['claude-code'] });

    expect(result.errors).toEqual([]);
    expect(result.files.map((f) => f.path).sort()).toEqual([
      '.claude/commands/deploy/preview/ship.md',
      '.claude/commands/ship.md',
    ]);
  });

  it('skips folder (.gitkeep) entries entirely — no file lands and no warning fires', () => {
    const paths = ['.outerlayer/commands/deploy/.gitkeep', '.outerlayer/AGENTS.md'];
    const contents = new Map([['.outerlayer/AGENTS.md', 'Root.\n']]);
    const result = emitTree({ entries: classifyTree(paths).entries, contents, assetPaths: [], targets: ['claude-code'] });

    expect(result.errors).toEqual([]);
    expect(result.warnings).toEqual([]);
    expect(result.files.map((f) => f.path)).toEqual(['CLAUDE.md']);
  });

  it('records a missing_content warning and skips the file, rather than throwing, when an entry has no source content', () => {
    const input = fixtureInput(['claude-code']);
    const contents = new Map(input.contents);
    contents.delete('.outerlayer/commands/ship.md');

    const result = emitTree({ ...input, contents });

    expect(result.warnings).toEqual([{ path: '.outerlayer/commands/ship.md', code: 'missing_content', message: 'no source content provided for ".outerlayer/commands/ship.md"' }]);
    expect(result.files.some((f) => f.path === '.claude/commands/ship.md')).toBe(false);
  });
});
