import { describe, expect, it, beforeEach, afterEach } from "vitest";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { runEmit, EmitError } from "../emit-cmd.js";

let root: string;

/** Matches emit/header.ts's `generatedHeader` exactly — not exported from the
 * OSS package's public barrel (target-builder internal), so pinned here as a
 * literal: a drift in that format is exactly what this test exists to catch. */
function header(sourcePath: string): string {
  return `<!-- generated by OuterLayer from ${sourcePath} — edit the source, not this file -->\n`;
}

function write(rootDir: string, relPath: string, content: string): void {
  const abs = join(rootDir, relPath);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, content);
}

/** Target selection comes only from .outerlayer/config.json (no --target flag). */
function writeConfig(rootDir: string, targets: string[]): void {
  write(rootDir, ".outerlayer/config.json", JSON.stringify({ targets }));
}

const MCP_JSON =
  '{\n  "mcpServers": {\n    "api": {\n      "url": "https://api.example.com",\n      "type": "http"\n    }\n  }\n}\n';

function writeFixture(rootDir: string): void {
  write(rootDir, ".outerlayer/AGENTS.md", "Root instructions.\n");
  write(
    rootDir,
    ".outerlayer/skills/deploy-checklist/SKILL.md",
    "---\nname: deploy-checklist\ndescription: Steps to deploy safely.\n---\nRun the checklist.\n",
  );
  write(rootDir, ".outerlayer/skills/deploy-checklist/scripts/run.sh", "#!/bin/sh\necho deploy\n");
  write(
    rootDir,
    ".outerlayer/skills/onboarding/SKILL.md",
    "---\nname: onboarding\ndescription: Onboard a new engineer.\n---\nRead the docs.\n",
  );
  write(rootDir, ".outerlayer/skills/onboarding/references/setup.md", "Install dependencies.\n");
  write(rootDir, ".outerlayer/skills/onboarding/assets/logo.png", "PNGDATA");
  write(rootDir, ".outerlayer/commands/ship.md", "---\ndescription: Ship the current branch.\n---\nRun the ship script.\n");
  write(rootDir, ".outerlayer/mcp.json", MCP_JSON);
  write(rootDir, "apps/api/.outerlayer/AGENTS.md", "API scope instructions.\n");
}

/** Reads back files in the given order (callers pass `result.files`, which
 * `emitTree` already sorts by `localeCompare` — re-sorting here with a plain
 * `.sort()` would use UTF-16 code-unit order instead and could disagree). */
function readWritten(rootDir: string, paths: string[]): Array<{ path: string; content: string }> {
  return paths.map((path) => ({ path, content: readFileSync(join(rootDir, path), "utf8") }));
}

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "ol-emit-"));
  writeFixture(root);
});
afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe("runEmit — claude-code target", () => {
  it("compiles the fixture tree into Claude Code's native layout, byte-exact", () => {
    writeConfig(root, ["claude-code"]);
    const result = runEmit({ cwd: root, quiet: true });

    expect(result.exitCode).toBe(0);
    expect(result.errors).toEqual([]);
    expect(result.files).toEqual([
      ".claude/commands/ship.md",
      ".claude/skills/deploy-checklist/SKILL.md",
      ".claude/skills/onboarding/references/setup.md",
      ".claude/skills/onboarding/SKILL.md",
      ".mcp.json",
      "apps/api/CLAUDE.md",
      "CLAUDE.md",
    ]);
    expect(result.copies).toEqual([
      ".claude/skills/deploy-checklist/scripts/run.sh",
      ".claude/skills/onboarding/assets/logo.png",
    ]);

    expect(readWritten(root, result.files)).toEqual(
      [
        {
          path: ".claude/commands/ship.md",
          content: header(".outerlayer/commands/ship.md") + "---\ndescription: Ship the current branch.\n---\nRun the ship script.\n",
        },
        {
          path: ".claude/skills/deploy-checklist/SKILL.md",
          content:
            header(".outerlayer/skills/deploy-checklist/SKILL.md") +
            "---\nname: deploy-checklist\ndescription: Steps to deploy safely.\n---\nRun the checklist.\n",
        },
        {
          path: ".claude/skills/onboarding/references/setup.md",
          content: header(".outerlayer/skills/onboarding/references/setup.md") + "Install dependencies.\n",
        },
        {
          path: ".claude/skills/onboarding/SKILL.md",
          content:
            header(".outerlayer/skills/onboarding/SKILL.md") +
            "---\nname: onboarding\ndescription: Onboard a new engineer.\n---\nRead the docs.\n",
        },
        { path: ".mcp.json", content: MCP_JSON },
        { path: "apps/api/CLAUDE.md", content: header("apps/api/.outerlayer/AGENTS.md") + "API scope instructions.\n" },
        { path: "CLAUDE.md", content: header(".outerlayer/AGENTS.md") + "Root instructions.\n" },
      ].sort((a, b) => a.path.localeCompare(b.path)),
    );

    // Copies are byte-identical to their sources.
    expect(readFileSync(join(root, ".claude/skills/deploy-checklist/scripts/run.sh"), "utf8")).toBe(
      readFileSync(join(root, ".outerlayer/skills/deploy-checklist/scripts/run.sh"), "utf8"),
    );
    expect(readFileSync(join(root, ".claude/skills/onboarding/assets/logo.png"), "utf8")).toBe(
      readFileSync(join(root, ".outerlayer/skills/onboarding/assets/logo.png"), "utf8"),
    );
  });
});

