describe("runEmit — codex target (AGENTS.md tier)", () => {
  it("emits AGENTS.md only, warning once per unsupported content kind present", () => {
    writeConfig(root, ["codex"]);
    const result = runEmit({ cwd: root, quiet: true });

    expect(result.exitCode).toBe(0);
    expect(result.errors).toEqual([]);
    expect(result.files).toEqual(["AGENTS.md", "apps/api/AGENTS.md"]);
    expect(result.copies).toEqual([]);
    expect(result.warnings).toEqual([
      { path: "codex:command", code: "unsupported_on_target", message: '"command" content is not emitted for codex (AGENTS.md-only tier in v1)' },
      { path: "codex:mcp", code: "unsupported_on_target", message: '"mcp" content is not emitted for codex (AGENTS.md-only tier in v1)' },
      { path: "codex:skill", code: "unsupported_on_target", message: '"skill" content is not emitted for codex (AGENTS.md-only tier in v1)' },
    ]);
    expect(readWritten(root, result.files)).toEqual([
      { path: "AGENTS.md", content: header(".outerlayer/AGENTS.md") + "Root instructions.\n" },
      { path: "apps/api/AGENTS.md", content: header("apps/api/.outerlayer/AGENTS.md") + "API scope instructions.\n" },
    ]);
  });
});

describe("runEmit — determinism", () => {
  it("two runs over the same tree, with the same config, produce byte-identical results", () => {
    writeConfig(root, ["claude-code", "cursor"]);
    const first = runEmit({ cwd: root, quiet: true });
    const second = runEmit({ cwd: root, quiet: true });

    expect(second.files).toEqual(first.files);
    expect(second.copies).toEqual(first.copies);
    expect(second.warnings).toEqual(first.warnings);
    expect(second.errors).toEqual(first.errors);
    expect(readWritten(root, second.files)).toEqual(readWritten(root, first.files));
  });
});

describe("runEmit — config refusal (no --target flag anywhere)", () => {
  it("throws EmitError, exit-worthy (1), and writes nothing when .outerlayer/config.json is absent", () => {
    expect(() => runEmit({ cwd: root, quiet: true })).toThrow(EmitError);
    expect(existsSync(join(root, "CLAUDE.md"))).toBe(false);
    expect(existsSync(join(root, ".claude"))).toBe(false);
  });

  it("throws EmitError with the exact actionable message when config is absent", () => {
    expect(() => runEmit({ cwd: root, quiet: true })).toThrow(EmitError);
    expect(() => runEmit({ cwd: root, quiet: true })).toThrow(
      'no .outerlayer/config.json with a non-empty targets array — create one, e.g. {"targets": ["claude-code"]}',
    );
  });

  it("refuses with the SAME actionable message, exit 1, and writes nothing when targets is an empty array", () => {
    writeConfig(root, []);

    expect(() => runEmit({ cwd: root, quiet: true })).toThrow(
      'no .outerlayer/config.json with a non-empty targets array — create one, e.g. {"targets": ["claude-code"]}',
    );
    expect(existsSync(join(root, "CLAUDE.md"))).toBe(false);
    expect(existsSync(join(root, ".claude"))).toBe(false);
  });

  it("surfaces the specific field error (not the generic refusal) for an unknown target id — the file DOES specify targets", () => {
    writeConfig(root, ["not-a-real-target"]);

    expect(() => runEmit({ cwd: root, quiet: true })).toThrow(EmitError);
    expect(() => runEmit({ cwd: root, quiet: true })).toThrow(/unknown target id "not-a-real-target"/);
    expect(existsSync(join(root, ".claude"))).toBe(false);
  });

  it("surfaces malformed JSON as an invalid-config error, not the generic missing-config refusal", () => {
    write(root, ".outerlayer/config.json", "{ targets: [");

    expect(() => runEmit({ cwd: root, quiet: true })).toThrow(/invalid \.outerlayer\/config\.json/);
    expect(existsSync(join(root, ".claude"))).toBe(false);
  });
});

describe("runEmit --json", () => {
  it("emits parsable JSON with the exact targets/files/copies/warnings/errors shape", () => {
    writeConfig(root, ["claude-code"]);
    const result = runEmit({ cwd: root, quiet: true, json: true });
    const parsed = JSON.parse(result.output) as {
      targets: string[];
      files: string[];
      copies: string[];
      warnings: unknown[];
      errors: unknown[];
    };
    expect(parsed).toEqual({
      targets: ["claude-code"],
      files: result.files,
      copies: result.copies,
      warnings: [],
      errors: [],
    });
  });
});

describe("runEmit --check", () => {
  it("a freshly emitted tree is clean — exit 0, empty drift", () => {
    writeConfig(root, ["claude-code"]);
    runEmit({ cwd: root, quiet: true });
    const result = runEmit({ cwd: root, check: true, quiet: true });
    expect(result.exitCode).toBe(0);
    expect(result.drift).toEqual([]);
    expect(result.files).toEqual([]);
    expect(result.copies).toEqual([]);
  });

  it("detects a missing output and writes nothing while reporting it", () => {
    writeConfig(root, ["claude-code"]);
    runEmit({ cwd: root, quiet: true });
    rmSync(join(root, "CLAUDE.md"));

    const result = runEmit({ cwd: root, check: true, quiet: true });

    expect(result.exitCode).toBe(1);
    expect(result.drift).toEqual([{ kind: "missing", path: "CLAUDE.md" }]);
    expect(existsSync(join(root, "CLAUDE.md"))).toBe(false); // --check never writes
  });

  it("detects content drift on an edited generated file and leaves it untouched", () => {
    writeConfig(root, ["claude-code"]);
    runEmit({ cwd: root, quiet: true });
    writeFileSync(join(root, ".claude/commands/ship.md"), "someone hand-edited this\n");

    const result = runEmit({ cwd: root, check: true, quiet: true });

    expect(result.exitCode).toBe(1);
    expect(result.drift).toEqual([{ kind: "content", path: ".claude/commands/ship.md" }]);
    // --check reports drift, it does not fix it.
    expect(readFileSync(join(root, ".claude/commands/ship.md"), "utf8")).toBe("someone hand-edited this\n");
  });

  it("a headerless user file sitting at a would-be output path is content drift, never silently overwritten", () => {
    writeConfig(root, ["claude-code"]);
    // No prior `emit` run — CLAUDE.md here is a genuine user file, not ours.
    write(root, "CLAUDE.md", "These are my own hand-written notes, not generated.\n");

    const result = runEmit({ cwd: root, check: true, quiet: true });

    expect(result.exitCode).toBe(1);
    expect(result.drift).toContainEqual({ kind: "content", path: "CLAUDE.md" });
    expect(readFileSync(join(root, "CLAUDE.md"), "utf8")).toBe(
      "These are my own hand-written notes, not generated.\n",
    );
  });

  it("flags a generated file as orphaned once its source is gone, and leaves it on disk", () => {
    writeConfig(root, ["claude-code"]);
    runEmit({ cwd: root, quiet: true });
    rmSync(join(root, ".outerlayer/AGENTS.md")); // the source CLAUDE.md was generated from

    const result = runEmit({ cwd: root, check: true, quiet: true });

    expect(result.exitCode).toBe(1);
    expect(result.drift).toContainEqual({ kind: "orphaned", path: "CLAUDE.md" });
    expect(existsSync(join(root, "CLAUDE.md"))).toBe(true); // reported, never deleted
  });

  it("does not flag a target's own output as orphaned just because a narrower config was checked", () => {
    // cursor's AGENTS.md derives from the same still-present source as claude-code's CLAUDE.md.
    writeConfig(root, ["claude-code", "cursor"]);
    runEmit({ cwd: root, quiet: true });
    writeConfig(root, ["claude-code"]);
    const result = runEmit({ cwd: root, check: true, quiet: true });
    expect(result.drift?.some((d) => d.path === "AGENTS.md")).toBe(false);
  });

  it("missing config still refuses under --check, exit 1, nothing written", () => {
    expect(() => runEmit({ cwd: root, check: true, quiet: true })).toThrow(EmitError);
    expect(existsSync(join(root, "CLAUDE.md"))).toBe(false);
  });

  it("--json shape for --check", () => {
    writeConfig(root, ["claude-code"]);
    runEmit({ cwd: root, quiet: true });
    const result = runEmit({ cwd: root, check: true, json: true, quiet: true });
    const parsed = JSON.parse(result.output) as { targets: string[]; drift: unknown[]; warnings: unknown[]; errors: unknown[] };
    expect(parsed).toEqual({ targets: ["claude-code"], drift: [], warnings: [], errors: [] });
  });
});
